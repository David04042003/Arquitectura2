-- Modelo relacional de la API Calendario (ver Diagramas/Punto2-API-Calendario.md)

CREATE TABLE IF NOT EXISTS tipo (
    id   INT         PRIMARY KEY,
    tipo VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS calendario (
    id          INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       DATE         NOT NULL UNIQUE,
    idtipo      INT          NOT NULL REFERENCES tipo (id),
    descripcion VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS ixcalendario_idtipo ON calendario (idtipo);

-- Usuarios con acceso a la API (seguridad por token)
CREATE TABLE IF NOT EXISTS usuario (
    id      INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50)  NOT NULL UNIQUE,
    nombre  VARCHAR(100) NOT NULL,
    clave   VARCHAR(100) NOT NULL,
    roles   VARCHAR(100)
);
