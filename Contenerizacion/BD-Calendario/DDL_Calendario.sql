-- Script de creación de la base de datos "calendario" (PostgreSQL).
-- Mismo modelo que API-Calendario/src/main/resources/schema.sql

CREATE DATABASE calendario;

-- Cambiar la conexión
\c calendario

/* Crear tabla TIPO (catálogo de tipos de día) */
CREATE TABLE IF NOT EXISTS tipo (
    id   INT         PRIMARY KEY,
    tipo VARCHAR(50) NOT NULL UNIQUE
);

/* Crear tabla CALENDARIO */
CREATE TABLE IF NOT EXISTS calendario (
    id          INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       DATE         NOT NULL UNIQUE,
    idtipo      INT          NOT NULL REFERENCES tipo (id),
    descripcion VARCHAR(100)
);

/* Crear índice para CALENDARIO ordenado por TIPO */
CREATE INDEX IF NOT EXISTS ixcalendario_idtipo ON calendario (idtipo);

/* Crear tabla USUARIO (seguridad por token) */
CREATE TABLE IF NOT EXISTS usuario (
    id      INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50)  NOT NULL UNIQUE,
    nombre  VARCHAR(100) NOT NULL,
    clave   VARCHAR(100) NOT NULL,
    roles   VARCHAR(100)
);
